from app.domain.post import Post


# Минимальная длина текста публикации, чтобы пройти грубый фильтр.
MIN_TEXT_LENGTH = 30


def passes_coarse_filter(post: Post) -> bool:
    """
    Грубый фильтр: отсекает слишком короткие публикации.

    Публикации с текстом короче MIN_TEXT_LENGTH символов считаются заведомо
    нерелевантными ("на сейчас", "актуально", "сколько по времени" и т.п.)
    и отбрасываются. Остальные проходят дальше на ML-фильтр.
    """

    return len(post.text) >= MIN_TEXT_LENGTH
