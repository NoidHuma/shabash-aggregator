import re


# Невидимые управляющие символы, которые встречаются в скопированных из
# Telegram/VK текстах и не несут смысла: zero-width, маркеры направления, BOM.
_ZERO_WIDTH = dict.fromkeys(
    map(ord, "​‌‍‎‏﻿"),
    None,
)

_WHITESPACE = re.compile(r"\s+")


def clean_text(text: str) -> str:
    """
    Нормализует текст ОДИНАКОВО при обучении и при инференсе.

    ВАЖНО: эта функция «зашита» в сохранённый pipeline (как preprocessor
    у TfidfVectorizer), поэтому она должна оставаться импортируемой по этому
    пути — иначе модель не загрузится в воркере. Не переименовывай и не
    превращай в lambda.

    Что делает (намеренно консервативно):
    - неразрывный пробел -> обычный;
    - удаляет zero-width / маркеры направления;
    - нижний регистр;
    - схлопывает любые пробельные последовательности в один пробел.

    Что НЕ трогает специально: цифры, '/', знаки, эмодзи — это сигнал
    ('500/2', '3000/8', обилие эмодзи у спама), их ловят char-н-граммы.
    """

    if not text:
        return ""

    text = text.replace("\xa0", " ")
    text = text.translate(_ZERO_WIDTH)
    text = text.lower()
    text = _WHITESPACE.sub(" ", text)

    return text.strip()
